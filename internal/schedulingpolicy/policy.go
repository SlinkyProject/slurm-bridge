// Package schedulingpolicy defines scheduling requests the bridge cannot honor.
// Keep these checks independent of admission and Slurm so all allocation entry
// points can enforce the same policy.
package schedulingpolicy

import (
	"reflect"
	"slices"
	"strconv"
	"strings"

	corev1 "k8s.io/api/core/v1"
	apiequality "k8s.io/apimachinery/pkg/api/equality"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	"k8s.io/apimachinery/pkg/runtime/schema"
	"k8s.io/apimachinery/pkg/util/validation/field"
)

// ValidatePod checks scheduling features, without rejecting metadata or
// ResourceClaims generated by the bridge itself.
func ValidatePod(pod *corev1.Pod) field.ErrorList {
	var errs field.ErrorList
	errs = append(errs, validatePreferredNodeAffinity(pod)...)
	errs = append(errs, validatePodAffinity(pod)...)
	errs = append(errs, validatePodAntiAffinity(pod)...)
	errs = append(errs, validateRequiredNodeAffinity(pod)...)
	errs = append(errs, validateTopologySpread(pod)...)
	errs = append(errs, validateInlineCSIVolumes(pod)...)
	return errs
}

// ValidateUpdate preserves existing violations on bound pods so an upgrade
// cannot prevent status, finalizer, or bridge metadata updates. New violations
// are still rejected. Unbound pods must satisfy the current policy.
func ValidateUpdate(oldPod, newPod *corev1.Pod) field.ErrorList {
	errs := ValidatePod(newPod)
	if len(errs) == 0 || oldPod.Spec.NodeName == "" || newPod.Spec.NodeName == "" {
		return errs
	}
	oldErrors := ValidatePod(oldPod)
	return slices.DeleteFunc(errs, func(err *field.Error) bool {
		if !slices.ContainsFunc(oldErrors, func(old *field.Error) bool { return old.Error() == err.Error() }) {
			return false
		}
		oldValue, oldOK := schedulingField(oldPod, err.Field)
		newValue, newOK := schedulingField(newPod, err.Field)
		return oldOK && newOK && apiequality.Semantic.DeepEqual(oldValue, newValue)
	})
}

// PodError returns a structured Kubernetes Invalid error with field paths.
func PodError(pod *corev1.Pod, errs field.ErrorList) error {
	if len(errs) == 0 {
		return nil
	}
	return apierrors.NewInvalid(schema.GroupKind{Kind: "Pod"}, pod.Name, errs)
}

// schedulingField reads the JSON field paths produced by this package, including
// container and volume indices. Unknown paths fail closed during grandfathering.
func schedulingField(pod *corev1.Pod, path string) (any, bool) {
	value := reflect.ValueOf(pod)
	path = strings.ReplaceAll(strings.ReplaceAll(path, "[", "."), "]", "")
	for _, segment := range strings.Split(path, ".") {
		for value.Kind() == reflect.Pointer {
			if value.IsNil() {
				return nil, false
			}
			value = value.Elem()
		}
		if value.Kind() == reflect.Slice {
			index, err := strconv.Atoi(segment)
			if err != nil || index < 0 || index >= value.Len() {
				return nil, false
			}
			value = value.Index(index)
			continue
		}
		if value.Kind() != reflect.Struct {
			return nil, false
		}
		found := false
		for _, property := range reflect.VisibleFields(value.Type()) {
			name, _, _ := strings.Cut(property.Tag.Get("json"), ",")
			if name == segment {
				value = value.FieldByIndex(property.Index)
				found = true
				break
			}
		}
		if !found {
			return nil, false
		}
	}
	if !value.IsValid() || !value.CanInterface() {
		return nil, false
	}
	return value.Interface(), true
}
